const fs = require('fs');
const path = require('path');

const targetPath = path.resolve('src/components/invoices/AeroWashQuoteBuilder.tsx');
let content = fs.readFileSync(targetPath, 'utf8');

// 1. Update lucide-react imports
if (!content.includes('RotateCcw,')) {
    content = content.replace(
        '    FileText\n} from "lucide-react"',
        '    FileText,\n    RotateCcw\n} from "lucide-react"'
    );
}

// 2. Update aerowash-catalogue imports
if (!content.includes('generateAeroWashScopeOfWorks,')) {
    content = content.replace(
        '    AEROWASH_STANDARD_TERMS_NAME\n} from "@/lib/aerowash-catalogue"',
        '    AEROWASH_STANDARD_TERMS_NAME,\n    generateAeroWashScopeOfWorks\n} from "@/lib/aerowash-catalogue"'
    );
}

// 3. Update AeroWashQuoteBuilderProps
if (!content.includes('siteName?: string;')) {
    content = content.replace(
        'export interface AeroWashQuoteBuilderProps {',
        'export interface AeroWashQuoteBuilderProps {\n    siteName?: string;'
    );
}

// 4. Update component argument destructuring
if (!content.includes('siteName = "",')) {
    content = content.replace(
        'export function AeroWashQuoteBuilder({\n    currencySymbol = "R",',
        'export function AeroWashQuoteBuilder({\n    siteName = "",\n    currencySymbol = "R",'
    );
}

// 5. Add Scope of Works state and logic after previewMode state
const stateMarker = "const [previewMode, setPreviewMode] = useState<'BUILDER' | 'CLIENT_VIEW'>('BUILDER');";
const scopeStateCode = `const [previewMode, setPreviewMode] = useState<'BUILDER' | 'CLIENT_VIEW'>('BUILDER');

    // 5. Scope of Works State & Auto-Generation
    const [scopeOfWorks, setScopeOfWorks] = useState<string>(() => {
        if (initialData?.scopeOfWorks) return initialData.scopeOfWorks;
        if (initialData?.metadata?.scopeOfWorks) return initialData.metadata.scopeOfWorks;
        return '';
    });
    const [isScopeEdited, setIsScopeEdited] = useState(false);

    const autoGeneratedScope = useMemo(() => {
        return generateAeroWashScopeOfWorks({
            siteName,
            elevationNames: elevations.map(e => e.name),
            hasGlazing: elevations.some(e => e.selectedCleaning === 'GLAZING' || e.selectedCleaning === 'BOTH_ALTERNATIVES'),
            hasFullFacade: elevations.some(e => e.selectedCleaning === 'FULL_FACADE' || e.selectedCleaning === 'BOTH_ALTERNATIVES'),
            hasRoofClean: siteProvisions.hasRoofClean,
            hasSolarClean: siteProvisions.hasSolarClean,
            hasSignage: siteProvisions.hasSignage,
            hasBirdFouling: siteProvisions.hasBirdFouling,
            hasStainPreTreatment: elevations.some(e => e.hasPreTreatment),
            hasPostConstruction: siteProvisions.hasPostConstruction,
            hasFacadeSurvey: siteProvisions.hasFacadeSurvey,
            hasThermalSurvey: siteProvisions.hasThermalSurvey,
        });
    }, [elevations, siteProvisions, siteName]);

    useEffect(() => {
        if (!isScopeEdited) {
            setScopeOfWorks(autoGeneratedScope);
        }
    }, [autoGeneratedScope, isScopeEdited]);

    const handleRegenerateScope = () => {
        setScopeOfWorks(autoGeneratedScope);
        setIsScopeEdited(false);
    };`;

if (!content.includes('// 5. Scope of Works State & Auto-Generation')) {
    content = content.replace(stateMarker, scopeStateCode);
}

// 6. Update onChange metadata to include scopeOfWorks and update dependency array
const oldOnChangeMetadata = `            metadata: {
                aerowashQuote: true,
                rateCardRevision: 13,
                elevations,`;

const newOnChangeMetadata = `            metadata: {
                aerowashQuote: true,
                rateCardRevision: 13,
                scopeOfWorks: scopeOfWorks || autoGeneratedScope,
                elevations,`;

if (!content.includes('scopeOfWorks: scopeOfWorks || autoGeneratedScope,')) {
    content = content.replace(oldOnChangeMetadata, newOnChangeMetadata);
    content = content.replace(
        '}, [calculation]);',
        '}, [calculation, scopeOfWorks, autoGeneratedScope]);'
    );
}

// 7. Insert Scope of Works Card in Builder view (before Contract Programmes)
const contractProgCardMarker = '{/* Contract Programmes (Whole Quote) */}';
const scopeCardMarkup = `{/* Scope of Works (Client-Facing) Card */}
                        <Card className="border-white/10 bg-[#0F172A]/70">
                            <CardHeader className="p-4 bg-white/[0.02] border-b border-white/5 flex flex-row items-center justify-between">
                                <div>
                                    <CardTitle className="text-sm font-bold uppercase tracking-wider flex items-center gap-2">
                                        <FileText className="w-4 h-4 text-primary" />
                                        Scope of Works (Client-Facing)
                                    </CardTitle>
                                    <CardDescription className="text-xs text-gray-400 mt-0.5">
                                        Plain client language only: never mention passes, pressures, chemicals, water volumes or methods. Carried through to the invoice.
                                    </CardDescription>
                                </div>
                                <Button
                                    type="button"
                                    variant="outline"
                                    size="sm"
                                    onClick={handleRegenerateScope}
                                    className="text-xs flex items-center gap-1.5 border-white/10 hover:border-primary/50 text-gray-300 hover:text-white"
                                >
                                    <RotateCcw className="w-3.5 h-3.5 text-primary" />
                                    Regenerate from items
                                </Button>
                            </CardHeader>
                            <CardContent className="p-4 space-y-2">
                                <textarea
                                    value={scopeOfWorks}
                                    onChange={(e) => {
                                        setScopeOfWorks(e.target.value);
                                        setIsScopeEdited(true);
                                    }}
                                    rows={3}
                                    className="w-full text-xs leading-relaxed rounded-xl bg-white/[0.03] border border-white/10 p-3 text-white focus:outline-none focus:border-primary resize-y"
                                    placeholder="Describe what will be done, at what site, on which elevations, and any provisions included..."
                                />
                                {isScopeEdited && (
                                    <p className="text-[11px] text-amber-400/90 flex items-center gap-1">
                                        <AlertTriangle className="w-3.5 h-3.5 shrink-0" />
                                        Customized manually. Click &quot;Regenerate from items&quot; to restore the auto-generated description.
                                    </p>
                                )}
                            </CardContent>
                        </Card>

                        {/* Contract Programmes (Whole Quote) */}`;

if (!content.includes('Scope of Works (Client-Facing) Card')) {
    content = content.replace(contractProgCardMarker, scopeCardMarkup);
}

// 8. Insert Scope of Works Block in Client View (before Client Lines Table)
const clientTableMarker = '{/* Client Lines Table */}';
const clientScopeMarkup = `{/* Scope of Works Block */}
                    <div className="p-4 rounded-xl bg-white/[0.02] border border-white/5 space-y-2">
                        <div className="text-[10px] font-black uppercase tracking-wider text-primary">
                            SCOPE OF WORKS
                        </div>
                        <p className="text-xs text-gray-300 leading-relaxed">
                            {scopeOfWorks || autoGeneratedScope}
                        </p>
                    </div>

                    {/* Client Lines Table */}`;

if (!content.includes('Scope of Works Block')) {
    content = content.replace(clientTableMarker, clientScopeMarkup);
}

fs.writeFileSync(targetPath, content, 'utf8');
console.log('Successfully patched AeroWashQuoteBuilder with Scope of Works!');
